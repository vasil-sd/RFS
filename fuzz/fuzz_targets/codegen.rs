//! Fuzz target: the code generators (Phase 6 task 5, D-P6-4).
//!
//! Invariant: random valid specs (specgen-backed) generate ALL six artifacts
//! (2 backends x production/test/mc) without error, and every artifact passes
//! cheap structural checks. No compilation inside the fuzzer - that lives in
//! the slow CI suite `tests/toolchain_fuzz_test.rs`.
//! Docs: dev:toolchain-fuzz-overview, llm:toolchain-fuzz

#![no_main]

mod common;

use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    let ir = common::rand_spec(data);
    let options = rfs::codegen::BackendOptions::default();
    for backend_name in ["rust", "c"] {
        let backend = rfs::codegen::get_backend(backend_name)
            .unwrap_or_else(|| panic!("backend {backend_name} must be registered"));
        for cmd in [
            rfs::codegen::CodegenCommandKind::Production,
            rfs::codegen::CodegenCommandKind::UnitTests,
            rfs::codegen::CodegenCommandKind::ModelChecker,
        ] {
            let out = cmd
                .run(backend, &ir, &options)
                .unwrap_or_else(|e| panic!("codegen {backend_name} {cmd:?} failed: {e:?}"));
            check_structure(backend_name, &out.code);
        }
    }
});

/// Cheap structural invariants over one generated artifact (string scans
/// only - keep this fast; it runs on every fuzzer iteration).
fn check_structure(backend: &str, code: &str) {
    // 1. Task-2 header on line 1 (toolchain version + spec hash field).
    let first = code.lines().next().unwrap_or("");
    assert!(
        first.starts_with("// Generated by RFS v") && first.contains("spec sha256:"),
        "artifact header malformed: {first:?}"
    );
    // 2. Balanced delimiters (line/block comments + string literals skipped).
    let mut bal = [0i32; 3]; // { } / ( ) / [ ]
    let bytes = code.as_bytes();
    let mut i = 0usize;
    while i < bytes.len() {
        let c = bytes[i];
        if c == b'/' && i + 1 < bytes.len() && bytes[i + 1] == b'/' {
            while i < bytes.len() && bytes[i] != b'\n' {
                i += 1;
            }
        } else if c == b'/' && i + 1 < bytes.len() && bytes[i + 1] == b'*' {
            i += 2;
            while i + 1 < bytes.len() && !(bytes[i] == b'*' && bytes[i + 1] == b'/') {
                i += 1;
            }
            i = (i + 2).min(bytes.len());
        } else if c == b'"' {
            i += 1;
            while i < bytes.len() && bytes[i] != b'"' {
                if bytes[i] == b'\\' {
                    i += 1;
                }
                i += 1;
            }
            i += 1;
        } else if c == b'\'' && i + 1 < bytes.len() && bytes[i + 1] == b'\\' {
            // Char literal with an escape (e.g. '\\'', '\\"', '\\n'): the
            // content is ONE escape sequence, so skip exactly opening quote +
            // backslash + one char, then the closing quote.
            i += 2;
            if i < bytes.len() {
                i += 1;
            }
            if i < bytes.len() && bytes[i] == b'\'' {
                i += 1;
            }
        } else if c == b'\'' && i + 2 < bytes.len() && bytes[i + 2] == b'\'' {
            // One-char literal (e.g. '\"', '{') - skip the triple. Lifetimes
            // ('a, 'static) do NOT match this shape and fall through below.
            i += 3;
        } else {
            match c {
                b'{' => bal[0] += 1,
                b'}' => bal[0] -= 1,
                b'(' => bal[1] += 1,
                b')' => bal[1] -= 1,
                b'[' => bal[2] += 1,
                b']' => bal[2] -= 1,
                _ => {}
            }
            i += 1;
        }
    }
    assert!(bal == [0, 0, 0], "unbalanced delimiters: {bal:?}");
    // 3. No placeholder tokens.
    if backend == "rust" {
        for tok in ["TODO", "FIXME", "PLACEHOLDER", "unimplemented!"] {
            assert!(
                !code.contains(tok),
                "placeholder token {tok:?} in Rust output"
            );
        }
    } else {
        assert!(
            !code.contains("TODO"),
            "placeholder token \"TODO\" in C output"
        );
    }
    // 4. Core symbols (verified against the backends during task planning).
    if backend == "rust" {
        assert!(
            code.contains("pub struct Fsm"),
            "missing `pub struct Fsm` in Rust output"
        );
    } else {
        assert!(
            code.contains("fsm_t") && code.contains("fsm_new"),
            "missing C core symbols (fsm_t/fsm_new)"
        );
    }
}
