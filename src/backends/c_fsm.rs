// Formula translation (C) - same translated safety subset as the Rust backend
// ---------------------------------------------------------------------------

impl<'a> Gen<'a> {
    fn emit_formula_functions(&mut self, warnings: &mut Vec<String>) {
        for p in &self.module.properties {
            if !validator::is_safety_formula(&p.formula) {
                warnings.push(format!("property '{}' is not safety; skipped", p.name));
                continue;
            }
            if let Some(code) = self.safety_formula_c(&p.name, &p.formula, "prop") {
                self.property_names.push(p.name.clone());
                self.code.push_str(&code);
            } else {
                warnings.push(format!(
                    "property '{}' is safety but outside the translated subset; skipped",
                    p.name
                ));
            }
        }
        for a in &self.module.assumptions {
            let selected = matches!(
                self.options.assumptions,
                crate::codegen::AssumptionSelection::All
            ) || matches!(&self.options.assumptions, crate::codegen::AssumptionSelection::Labels(l) if l.iter().any(|x| x == &a.name));
            if !selected {
                continue;
            }
            if !validator::is_safety_formula(&a.formula) {
                warnings.push(format!("assume '{}' is not safety; skipped", a.name));
                continue;
            }
            if let Some(code) = self.safety_formula_c(&a.name, &a.formula, "assume") {
                self.active_assumes.push(a.name.clone());
                self.code.push_str(&code);
            } else {
                warnings.push(format!(
                    "assume '{}' is safety but outside the translated subset; skipped",
                    a.name
                ));
            }
        }

        let props: Vec<String> = if self.property_names.is_empty() {
            vec!["0".into()]
        } else {
            self.property_names
                .iter()
                .map(|s| format!("\"{}\"", s))
                .collect()
        };
        let assumes: Vec<String> = if self.active_assumes.is_empty() {
            vec!["0".into()]
        } else {
            self.active_assumes
                .iter()
                .map(|s| format!("\"{}\"", s))
                .collect()
        };
        let _ = writeln!(
            self.code,
            "static const char* PROPERTY_LABELS[] = {{{}}};",
            props.join(", ")
        );
        let _ = writeln!(
            self.code,
            "static const int N_PROPERTY_LABELS = {};",
            self.property_names.len()
        );
        let _ = writeln!(
            self.code,
            "static const char* ASSUME_LABELS[] = {{{}}};",
            assumes.join(", ")
        );
        let _ = writeln!(
            self.code,
            "static const int N_ASSUME_LABELS = {};",
            self.active_assumes.len()
        );

        // Dispatchers used by the model checker and commit_step.
        let mut pm = String::new();
        for n in &self.property_names {
            let _ = writeln!(
                pm,
                "    if (strcmp(label, \"{}\") == 0) return prop_{}_always(trace);",
                n,
                crate::backends::rust::snake(n)
            );
        }
        let mut am = String::new();
        for n in &self.active_assumes {
            let _ = writeln!(
                am,
                "    if (strcmp(label, \"{}\") == 0) return assume_{}_always(trace);",
                n,
                crate::backends::rust::snake(n)
            );
        }
        let _ = writeln!(
            self.code,
            "static bool rfs_property_check(const char* label, const rfs_trace_t* trace) {{ (void)label; (void)trace;\n{pm}    return true;\n}}\n\
             static bool rfs_assume_check(const char* label, const rfs_trace_t* trace) {{ (void)label; (void)trace;\n{am}    return true;\n}}"
        );
    }

    fn safety_formula_c(&self, name: &str, formula: &Formula, prefix: &str) -> Option<String> {
        let inner = codegen_fsm::safety_formula_inner(formula)?;
        let sname = crate::backends::rust::snake(name);
        // Collect distinct InputIs/OutputHas patterns for helper functions.
        let mut input_pats: Vec<&EventPattern> = Vec::new();
        let mut output_pats: Vec<&OutputPattern> = Vec::new();
        let mut stack = vec![inner];
        while let Some(f) = stack.pop() {
            match f {
                Formula::InputIs { pattern } => input_pats.push(pattern),
                Formula::OutputHas { pattern } => output_pats.push(pattern),
                _ => {}
            }
            match f {
                Formula::Not { inner } | Formula::Next { inner } => stack.push(inner),
                Formula::And { left, right }
                | Formula::Or { left, right }
                | Formula::Implies { left, right } => {
                    stack.push(left);
                    stack.push(right);
                }
                _ => {}
            }
        }
        let mut helpers = String::new();
        for (i, p) in input_pats.iter().enumerate() {
            if let Some(h) = self.input_is_helper_c(*p, i) {
                helpers.push_str(&h);
            } else {
                return None;
            }
        }
        for (i, p) in output_pats.iter().enumerate() {
            if let Some(h) = self.output_has_helper_c(*p, i) {
                helpers.push_str(&h);
            } else {
                return None;
            }
        }
        let at_body = self.gen_formula_c(inner, "pos", &input_pats, &output_pats)?;
        Some(format!(
            "{helpers}static bool {}_{}(const rfs_trace_t* trace, int pos) {{ return {}; }}\n\
             static bool {}_{}_always(const rfs_trace_t* trace) {{ for (int pos = 0; pos <= trace->len; pos++) {{ if (!{}_{}(trace, pos)) return false; }} return true; }}\n",
            prefix, sname, at_body, prefix, sname, prefix, sname
        ))
    }

    /// Render a formula over a trace position. `pos_expr` is the C expression
    /// for the current position (e.g. "pos" or "pos + 1").
    fn gen_formula_c(
        &self,
        f: &Formula,
        pos_expr: &str,
        input_pats: &[&EventPattern],
        output_pats: &[&OutputPattern],
    ) -> Option<String> {
        match f {
            Formula::Expr { expr } => {
                let env = Env::for_module(self.module);
                let mut ctx = Ctx::default();
                for v in &self.module.vars {
                    ctx.names.insert(
                        v.name.clone(),
                        format!("trace_vars(trace, {}).{}", pos_expr, c_ident(&v.name)),
                    );
                }
                ctx.state_variants = self
                    .module
                    .enums
                    .iter()
                    .find(|e| e.name == "State")
                    .map(|e| e.variants.iter().cloned().collect())
                    .unwrap_or_default();
                ctx.names
                    .insert("state".into(), format!("trace_state(trace, {})", pos_expr));
                gen_expr_c(expr, &env, &ctx, self.module).ok()
            }
            Formula::Not { inner } => Some(format!(
                "(!({}))",
                self.gen_formula_at_inner(inner, pos_expr, input_pats, output_pats)?
            )),
            Formula::And { left, right } => Some(format!(
                "(({}) && ({})",
                self.gen_formula_at_inner(left, pos_expr, input_pats, output_pats)?,
                self.gen_formula_at_inner(right, pos_expr, input_pats, output_pats)?
            )),
            Formula::Or { left, right } => Some(format!(
                "(({}) || ({})",
                self.gen_formula_at_inner(left, pos_expr, input_pats, output_pats)?,
                self.gen_formula_at_inner(right, pos_expr, input_pats, output_pats)?
            )),
            Formula::Implies { left, right } => Some(format!(
                "(!({}) || ({})",
                self.gen_formula_at_inner(left, pos_expr, input_pats, output_pats)?,
                self.gen_formula_at_inner(right, pos_expr, input_pats, output_pats)?
            )),
            Formula::Next { inner } => Some(format!(
                "(({} + 1 <= trace->len && {}))",
                pos_expr,
                self.gen_formula_at_inner(
                    inner,
                    &(format!("({} + 1)", pos_expr)),
                    input_pats,
                    output_pats
                )?
            )),
            Formula::InputIs { pattern } => {
                let idx = input_pats.iter().position(|p| *p == pattern)?;
                Some(format!("input_is_{}(trace, {})", idx, pos_expr))
            }
            Formula::OutputHas { pattern } => {
                let idx = output_pats.iter().position(|p| *p == pattern)?;
                Some(format!("output_has_{}(trace, {})", idx, pos_expr))
            }
            _ => None,
        }
    }

    fn gen_formula_at_inner(
        &self,
        f: &Formula,
        pos_expr: &str,
        input_pats: &[&EventPattern],
        output_pats: &[&OutputPattern],
    ) -> Option<String> {
        self.gen_formula_c(f, pos_expr, input_pats, output_pats)
    }

    /// Helper: does the trace input at `pos` match this pattern?
    fn input_is_helper_c(&self, pattern: &EventPattern, idx: usize) -> Option<String> {
        let cond = self.input_match_cond(pattern)?;
        Some(format!(
            "static bool input_is_{}(const rfs_trace_t* trace, int pos) {{ if (pos >= trace->len) return false; const input_t* inp = &trace->steps[pos].input; return {}; }}\n",
            idx, cond
        ))
    }

    /// Helper: does the trace step at `pos` contain an output matching this pattern?
    fn output_has_helper_c(&self, pattern: &OutputPattern, idx: usize) -> Option<String> {
        let cond = self.output_match_cond(pattern)?;
        Some(format!(
            "static bool output_has_{}(const rfs_trace_t* trace, int pos) {{ if (pos >= trace->len) return false; for (int i = 0; i < trace->steps[pos].n_outputs; i++) {{ const output_t* o = &trace->steps[pos].outputs[i]; if ({cond}) return true; }} return false; }}\n",
            idx
        ))
    }

    /// C condition for an input matching a pattern (over `inp`).
    fn input_match_cond(&self, pattern: &EventPattern) -> Option<String> {
        match &pattern.variant {
            None => {
                let variants: Vec<&VariantInfo> = self
                    .variants
                    .inputs
                    .iter()
                    .filter(|v| v.group == pattern.group)
                    .collect();
                if variants.is_empty() {
                    return None;
                }
                let arms: Vec<String> = variants
                    .iter()
                    .map(|v| format!("inp->kind == INPUT_{}", v.unique_name.to_uppercase()))
                    .collect();
                Some(arms.join(" || "))
            }
            Some(PatternVariant::Unit { name }) => {
                let v = self.variants.input_variant(&pattern.group, name)?;
                if !v.fields.is_empty() {
                    return None;
                }
                Some(format!(
                    "inp->kind == INPUT_{}",
                    v.unique_name.to_uppercase()
                ))
            }
            Some(PatternVariant::Struct { name, fields }) => {
                let v = self.variants.input_variant(&pattern.group, name)?;
                if v.fields.len() != fields.len() {
                    return None;
                }
                let pl = format!("inp->payload.input_{}", v.unique_name.to_lowercase());
                let mut guards: Vec<String> = vec![format!(
                    "inp->kind == INPUT_{}",
                    v.unique_name.to_uppercase()
                )];
                for (i, pf) in fields.iter().enumerate() {
                    let fname = c_ident(&v.fields[i].0);
                    match &pf.pattern {
                        PatternExpr::Int { value } => guards.push(format!(
                            "{}.{} == {}",
                            pl,
                            fname,
                            int_c_literal(*value, None)
                        )),
                        PatternExpr::Bool { value } => guards.push(format!(
                            "{}.{} == {}",
                            pl,
                            fname,
                            if *value { "true" } else { "false" }
                        )),
                        PatternExpr::EnumVariant { path } => {
                            let base = c_ident(&path[0]);
                            let rest = path[1..]
                                .iter()
                                .map(|x| c_ident(x).to_uppercase())
                                .collect::<Vec<_>>()
                                .join("_");
                            guards.push(format!(
                                "{}.{} == {}_{}",
                                pl,
                                fname,
                                base.to_uppercase(),
                                rest
                            ));
                        }
                        _ => {} // wildcard / bind: no constraint
                    }
                }
                Some(guards.join(" && "))
            }
        }
    }

    /// C condition for an output matching a pattern (over `o`).
    fn output_match_cond(&self, pattern: &OutputPattern) -> Option<String> {
        match &pattern.variant {
            None => {
                let variants: Vec<&VariantInfo> = self
                    .variants
                    .outputs
                    .iter()
                    .filter(|v| v.group == pattern.group)
                    .collect();
                if variants.is_empty() {
                    return None;
                }
                let arms: Vec<String> = variants
                    .iter()
                    .map(|v| format!("o->kind == OUTPUT_{}", v.unique_name.to_uppercase()))
                    .collect();
                Some(arms.join(" || "))
            }
            Some(PatternVariant::Unit { name }) => {
                let v = self.variants.output_variant(&pattern.group, name)?;
                if !v.fields.is_empty() {
                    return None;
                }
                Some(format!(
                    "o->kind == OUTPUT_{}",
                    v.unique_name.to_uppercase()
                ))
            }
            Some(PatternVariant::Struct { name, fields }) => {
                let v = self.variants.output_variant(&pattern.group, name)?;
                if v.fields.len() != fields.len() {
                    return None;
                }
                let pl = format!("o->payload.output_{}", v.unique_name.to_lowercase());
                let mut guards: Vec<String> = vec![format!(
                    "o->kind == OUTPUT_{}",
                    v.unique_name.to_uppercase()
                )];
                for (i, pf) in fields.iter().enumerate() {
                    let fname = c_ident(&v.fields[i].0);
                    match &pf.pattern {
                        PatternExpr::Int { value } => guards.push(format!(
                            "{}.{} == {}",
                            pl,
                            fname,
                            int_c_literal(*value, None)
                        )),
                        PatternExpr::Bool { value } => guards.push(format!(
                            "{}.{} == {}",
                            pl,
                            fname,
                            if *value { "true" } else { "false" }
                        )),
                        PatternExpr::EnumVariant { path } => {
                            let base = c_ident(&path[0]);
                            let rest = path[1..]
                                .iter()
                                .map(|x| c_ident(x).to_uppercase())
                                .collect::<Vec<_>>()
                                .join("_");
                            guards.push(format!(
                                "{}.{} == {}_{}",
                                pl,
                                fname,
                                base.to_uppercase(),
                                rest
                            ));
                        }
                        _ => {}
                    }
                }
                Some(guards.join(" && "))
            }
        }
    }
}

impl<'a> Gen<'a> {
    /// Emit the fsm struct, constructor, commit_step, and priority-ordered step.
    fn emit_fsm_impl(&mut self) -> Result<(), String> {
        let m = self.module;
        let init_state = m.initial_state.clone().unwrap_or_else(|| "__None__".into());

        let _ = writeln!(
            self.code,
            "typedef struct {{ state_t state; vars_t vars; rfs_trace_t trace; const char** active_assumes; int n_active_assumes; }} fsm_t;"
        );

        // Initial vars literal.
        let init_vars = if m.vars.is_empty() {
            "(vars_t){0}".to_string()
        } else {
            let env = Env::for_module(m);
            let mut ctx = Ctx::default();
            for v in &m.vars {
                ctx.names
                    .insert(v.name.clone(), format!("vars.{}", c_ident(&v.name)));
            }
            // Build via a temporary struct initializer using the init expressions.
            let fields: Vec<String> = m
                .vars
                .iter()
                .map(|v| {
                    gen_expr_c(&v.init, &env, &ctx, m)
                        .map(|e| format!(".{} = {}", c_ident(&v.name), e))
                        .or(Ok(format!(".{} = 0", c_ident(&v.name))))
                })
                .collect::<Result<Vec<String>, String>>()?;
            format!("(vars_t){{ {} }}", fields.join(", "))
        };

        let _ = writeln!(
            self.code,
            "void fsm_new(fsm_t* f) {{\n    f->state = STATE_{};\n    f->vars = {};\n    f->trace.initial_state = f->state; f->trace.initial_vars = f->vars; f->trace.steps = 0; f->trace.len = 0; f->trace.cap = 0;\n    f->n_active_assumes = N_ASSUME_LABELS;\n    f->active_assumes = (const char**)calloc((size_t)f->n_active_assumes, sizeof(char*));\n    for (int i = 0; i < f->n_active_assumes; i++) f->active_assumes[i] = ASSUME_LABELS[i];\n}}",
            c_ident(&init_state).to_uppercase(),
            init_vars
        );

        // commit_step: push trace, check active assumptions via handler.
        let _ = writeln!(
            self.code,
            "static step_result_t rfs_commit(fsm_t* f, const input_t* in, const output_t* outs, int n_out, state_t next_state, const vars_t* new_vars, rfs_assumption_handler handler, void* user) {{\n    trace_step_t s; s.input = *in; for (int i = 0; i < n_out && i < MAX_OUTPUTS; i++) s.outputs[i] = outs[i]; s.n_outputs = n_out; s.from = f->state; s.to = next_state; s.vars = *new_vars;\n    trace_push(&f->trace, &s);\n    for (int i = 0; i < f->n_active_assumes; i++) {{\n        if (!rfs_assume_check(f->active_assumes[i], &f->trace)) {{\n            rfs_policy_t pol = handler(user, f->active_assumes[i]);\n            if (pol == RFS_STOP) {{ step_result_t r; r.status = RFS_ASSUMPTION_VIOLATION; strncpy(r.assume_label, f->active_assumes[i], sizeof(r.assume_label) - 1); r.assume_label[sizeof(r.assume_label) - 1] = 0; r.n_outputs = 0; return r; }}\n            if (pol == RFS_PANIC) {{ fprintf(stderr, \"RFS assumption violated: %s\\n\", f->active_assumes[i]); abort(); }}\n        }}\n    }}\n    f->state = next_state; f->vars = *new_vars;\n    step_result_t r; r.status = RFS_OK; for (int i = 0; i < n_out && i < MAX_OUTPUTS; i++) r.outputs[i] = outs[i]; r.n_outputs = n_out; r.assume_label[0] = 0; return r;\n}}"
        );

        // step(): grouped by state, priority-ordered within a state (Phase 2).
        let _ = writeln!(
            self.code,
            "step_result_t fsm_step(fsm_t* f, input_t in, rfs_assumption_handler handler, void* user) {{\n    if (handler == 0) handler = rfs_panic_handler;"
        );

        let mut state_order: Vec<&str> = Vec::new();
        let mut by_state: std::collections::HashMap<&str, Vec<usize>> =
            std::collections::HashMap::new();
        for (idx, t) in m.transitions.iter().enumerate() {
            if !by_state.contains_key(t.state.as_str()) {
                state_order.push(t.state.as_str());
            }
            by_state.entry(t.state.as_str()).or_default().push(idx);
        }
        for state in &state_order {
            let mut idxs: Vec<usize> = by_state.get(state).unwrap().clone();
            idxs.sort_by_key(|&k| std::cmp::Reverse(m.transitions[k].priority.unwrap_or(0)));
            let _ = writeln!(
                self.code,
                "    if (f->state == STATE_{}) {{",
                c_ident(state).to_uppercase()
            );
            for idx in idxs {
                self.code
                    .push_str(&self.transition_block_c(&m.transitions[idx])?);
            }
            let _ = writeln!(self.code, "    }}");
        }

        if let Some(oe) = &m.on_error {
            // on_error fallback (Phase 2): no state check, no bindings.
            let mut ctx = Ctx::default();
            for v in &m.vars {
                ctx.names
                    .insert(v.name.clone(), format!("f->vars.{}", c_ident(&v.name)));
            }
            let env = Env::for_module(m);
            let mut outs: Vec<String> = Vec::new();
            for o in &oe.emits {
                outs.push(self.output_expr_c(o, &env, &ctx)?);
            }
            let _ = writeln!(
                self.code,
                "    // on_error fallback: no transition matched the input"
            );
            let _ = writeln!(self.code, "    {{");
            let _ = writeln!(
                self.code,
                "        output_t outs[MAX_OUTPUTS]; int n_out = {};",
                outs.len()
            );
            for (i, o) in outs.iter().enumerate() {
                let _ = writeln!(self.code, "        outs[{}] = {};", i, o);
            }
            let _ = writeln!(
                self.code,
                "        return rfs_commit(f, &in, outs, n_out, STATE_{}, &f->vars, handler, user);",
                c_ident(&oe.next_state).to_uppercase()
            );
            let _ = writeln!(self.code, "    }}");
        } else {
            let _ = writeln!(
                self.code,
                "    {{ step_result_t r; r.status = RFS_UNEXPECTED_EVENT; r.n_outputs = 0; r.assume_label[0] = 0; return r; }}"
            );
        }
        let _ = writeln!(self.code, "}}");
        Ok(())
    }

    /// Render one transition as nested if-blocks: state (emitted by caller) ->
    /// pattern match (bindings become local variables) -> guard -> actions.
    fn transition_block_c(&self, t: &Transition) -> Result<String, String> {
        let m = self.module;
        let mut out = String::new();

        // Pattern: kind check + bindings as locals + field constraints.
        match &t.pattern.variant {
            None => {
                let variants: Vec<&VariantInfo> = self
                    .variants
                    .inputs
                    .iter()
                    .filter(|v| v.group == t.pattern.group)
                    .collect();
                if variants.is_empty() {
                    return Err(format!("unknown event group '{}'", t.pattern.group));
                }
                let arms: Vec<String> = variants
                    .iter()
                    .map(|v| format!("in.kind == INPUT_{}", v.unique_name.to_uppercase()))
                    .collect();
                let _ = writeln!(out, "        if ({}) {{", arms.join(" || "));
            }
            Some(PatternVariant::Unit { name }) => {
                let v = self
                    .variants
                    .input_variant(&t.pattern.group, name)
                    .ok_or_else(|| {
                        format!(
                            "unknown event variant '{}' in group '{}'",
                            name, t.pattern.group
                        )
                    })?;
                if !v.fields.is_empty() {
                    return Err("unit pattern on struct variant".into());
                }
                let _ = writeln!(
                    out,
                    "        if (in.kind == INPUT_{}) {{",
                    v.unique_name.to_uppercase()
                );
            }
            Some(PatternVariant::Struct { name, fields }) => {
                let v = self
                    .variants
                    .input_variant(&t.pattern.group, name)
                    .ok_or_else(|| {
                        format!(
                            "unknown event variant '{}' in group '{}'",
                            name, t.pattern.group
                        )
                    })?;
                if v.fields.len() != fields.len() {
                    return Err("pattern field count mismatch".into());
                }
                let pl = format!("in.payload.input_{}", v.unique_name.to_lowercase());
                let mut conds: Vec<String> =
                    vec![format!("in.kind == INPUT_{}", v.unique_name.to_uppercase())];
                for (i, pf) in fields.iter().enumerate() {
                    let fname = c_ident(&v.fields[i].0);
                    match &pf.pattern {
                        PatternExpr::Int { value } => conds.push(format!(
                            "{}.{} == {}",
                            pl,
                            fname,
                            int_c_literal(*value, None)
                        )),
                        PatternExpr::Bool { value } => conds.push(format!(
                            "{}.{} == {}",
                            pl,
                            fname,
                            if *value { "true" } else { "false" }
                        )),
                        PatternExpr::EnumVariant { path } => {
                            let base = c_ident(&path[0]);
                            let rest = path[1..]
                                .iter()
                                .map(|x| c_ident(x).to_uppercase())
                                .collect::<Vec<_>>()
                                .join("_");
                            conds.push(format!(
                                "{}.{} == {}_{}",
                                pl,
                                fname,
                                base.to_uppercase(),
                                rest
                            ));
                        }
                        _ => {}
                    }
                }
                let _ = writeln!(out, "        if ({}) {{", conds.join(" && "));
            }
        }

        // Bindings as local variables (in declared field order).
        let mut env = Env::for_module(m);
        let mut ctx = Ctx::default();
        for v in &m.vars {
            ctx.names
                .insert(v.name.clone(), format!("f->vars.{}", c_ident(&v.name)));
        }
        ctx.state_variants = m
            .enums
            .iter()
            .find(|e| e.name == "State")
            .map(|e| e.variants.iter().cloned().collect())
            .unwrap_or_default();
        ctx.names.insert("state".into(), "f->state".into());

        if let Some(PatternVariant::Struct { name, fields, .. }) = &t.pattern.variant {
            let v = self
                .variants
                .input_variant(&t.pattern.group, name)
                .ok_or("pattern variant lookup")?;
            let pl = format!("in.payload.input_{}", v.unique_name.to_lowercase());
            for (i, pf) in fields.iter().enumerate() {
                if let PatternExpr::Bind { name } = &pf.pattern {
                    let fname = c_ident(&v.fields[i].0);
                    let ty = c_type(&v.fields[i].1).map_err(|e| e.to_string())?;
                    let _ = writeln!(
                        out,
                        "            {} {} = {}.{};",
                        ty,
                        c_ident(name),
                        pl,
                        fname
                    );
                    env.bindings.insert(
                        name.clone(),
                        crate::validator::type_to_expr_type(&v.fields[i].1),
                    );
                }
            }
        }
        for name in env.bindings.keys() {
            ctx.names.insert(name.clone(), c_ident(name));
        }

        // Guard.
        if let Some(g) = &t.guard {
            let gexpr = gen_expr_c(g, &env, &ctx, m)?;
            let _ = writeln!(out, "            if ({}) {{", gexpr);
        }

        // Actions: outputs, next state, simultaneous var updates via temps.
        let mut outs: Vec<String> = Vec::new();
        for o in &t.emits {
            outs.push(self.output_expr_c(o, &env, &ctx)?);
        }
        let _ = writeln!(
            out,
            "            output_t outs[MAX_OUTPUTS]; int n_out = {};",
            outs.len()
        );
        for (i, o) in outs.iter().enumerate() {
            let _ = writeln!(out, "            outs[{}] = {};", i, o);
        }

        if m.vars.is_empty() {
            let _ = writeln!(
                out,
                "            return rfs_commit(f, &in, outs, n_out, STATE_{}, &f->vars, handler, user);",
                c_ident(&t.next_state).to_uppercase()
            );
        } else {
            // Simultaneous update: start from current vars, evaluate all RHS
            // into temps (old values only), then assign.
            let _ = writeln!(out, "            vars_t tmp_vars = f->vars;");
            for a in &t.assignments {
                let val = gen_expr_c(&a.value, &env, &ctx, m)?;
                let ty = c_type(
                    &m.vars
                        .iter()
                        .find(|v| v.name == a.var)
                        .map(|v| &v.ty)
                        .unwrap_or(&Type::Bool),
                )
                .map_err(|e| e.to_string())?;
                let _ = writeln!(out, "            {} tmp_{} = {};", ty, c_ident(&a.var), val);
            }
            for a in &t.assignments {
                let _ = writeln!(
                    out,
                    "            tmp_vars.{} = tmp_{};",
                    c_ident(&a.var),
                    c_ident(&a.var)
                );
            }
            let _ = writeln!(
                out,
                "            return rfs_commit(f, &in, outs, n_out, STATE_{}, &tmp_vars, handler, user);",
                c_ident(&t.next_state).to_uppercase()
            );
        }

        if t.guard.is_some() {
            let _ = writeln!(out, "            }}");
        }
        let _ = writeln!(out, "        }}");
        Ok(out)
    }

    /// Render an output expression as a C initializer for `output_t`.
    fn output_expr_c(&self, o: &OutputExpr, env: &Env, ctx: &Ctx) -> Result<String, String> {
        let variant = match &o.variant {
            Some(v) => v.clone(),
            None => {
                let g = self
                    .module
                    .outputs
                    .iter()
                    .find(|g| g.name == o.group)
                    .ok_or("unknown output group")?;
                if g.variants.len() != 1 {
                    return Err("bare output ambiguous".into());
                }
                match &g.variants[0] {
                    ConstructorVariant::Unit { name } => name.clone(),
                    ConstructorVariant::Struct { name, .. } => name.clone(),
                }
            }
        };
        let v = self
            .variants
            .output_variant(&o.group, &variant)
            .ok_or("unknown output variant")?;
        if v.fields.is_empty() {
            return Ok(format!(
                "(output_t){{ .kind = OUTPUT_{} }}",
                v.unique_name.to_uppercase()
            ));
        }
        if v.fields.len() != o.args.len() {
            return Err(format!(
                "output {}({}) expects {} args, got {}",
                o.group,
                variant,
                v.fields.len(),
                o.args.len()
            ));
        }
        let pl = format!("payload.output_{}", v.unique_name.to_lowercase());
        let mut fields = vec![format!(".kind = OUTPUT_{}", v.unique_name.to_uppercase())];
        for (i, a) in o.args.iter().enumerate() {
            let val = gen_expr_c(a, env, ctx, self.module)?;
            fields.push(format!(".{}.{} = {}", pl, c_ident(&v.fields[i].0), val));
        }
        Ok(format!("(output_t){{ {} }}", fields.join(", ")))
    }
}
