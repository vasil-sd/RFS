//! Seeded random-testing engine for `rfs mc-ref --mode fuzz` (Phase 16 task 3,
//! D-P16-4 / D-P16-5). Independent ground truth for the generated fuzz
//! runtimes: it reproduces their EXACT RNG draw sequence (shared LCG via
//! `utils::rng`) and their byte-format per-run violation reports + summary
//! line, built on the `ref_mc` common core with deliberately different data
//! structures (no bit-packing, own trace record). The generated runtimes step
//! DETERMINISTICALLY (first matching transition; fuzz randomizes inputs, not
//! transitions), so this engine uses `match_effect` - no nondet involvement.
//!
//! Draw-sequence contract (mirrors the generated `run_fuzz` step for step):
//! per run, (1) `chance(spec.prob)` per violation spec in order -> `violating`;
//! per step, (2a) forced phase - for each active spec in order, `chance(
//! target_fraction)` then a DRAW-FREE scan of all inputs (clone + first-match
//! trial) for one whose trial yields the spec's label; (2b) unexpected phase -
//! `chance(unexpected_prob)` then `pick_index(fuzz_inputs)`; (2c) allowed phase
//! - a draw-free scan builds the allowed list, then `pick_index(allowed)`. Trial
//! steps consume NO draws. A property violation exits immediately (report,
//! exit 1, no summary line); otherwise the summary line prints after all runs.
//!
//! Docs: dev:mc-engine-overview, dev:mc-engine-fuzz, llm:mc-engine

use super::ref_mc::{
    compile_formula, contains_liveness, flatten, fuzz_inputs, initial_config, match_effect,
    mon_init, mon_step, render_input, render_outputs, render_vars, state_variants, FlatVariant,
    FuzzConfig, InputVal, IoRec, Mon, MonSt, OutputVal, Sample, Val,
};
use crate::codegen::mc_concepts::{fuzz_summary_line, parse_assume_selection};
use crate::lang::ir::*;
use crate::utils::rng::Rng;

/// The outcome of a fuzz-mode run: either all runs completed (summary line,
/// exit 0) or a property violation terminated a run (per-run report, exit 1,
/// NO summary line - the generated binaries `exit(1)` before printing it).
#[derive(Debug)]
pub enum FuzzReport {
    /// Every run finished; `summary` is the single summary line.
    Completed { summary: String },
    /// A property violation ended a run early; `report` is the per-run
    /// violation report (the generated binaries print exactly this, then exit).
    Violated { report: String },
}

/// One recorded trace step (input, emitted outputs, from/to state indices,
/// post-step vars) - the ref-mc analogue of the generated `TraceStep`.
#[derive(Clone)]
struct TraceStep {
    input: InputVal,
    outputs: Vec<OutputVal>,
    from_state: usize,
    to_state: usize,
    vars: Vec<Val>,
}

/// The fuzz FSM: control state + vars + the two monitor banks (properties and
/// ALL assumptions - the selection filters at step time, mirroring the
/// generated `active_assumes`) + the trace. The compiled specs are immutable
/// shared data passed to [`step_fsm`], not stored here.
#[derive(Clone)]
struct FuzzFsm {
    state: usize,
    vars: Vec<Val>,
    prop_mons: Vec<MonSt>,
    assume_mons: Vec<MonSt>,
    trace: Vec<TraceStep>,
}

/// A step's failure mode (the generated `StepError` analogue).
enum StepErr {
    AssumptionViolation(String),
    PropertyViolation {
        label: String,
        trigger: Option<usize>,
        step: usize,
    },
    UnexpectedEvent,
}

/// Convert a flattened input to its wire record for the renderers.
fn io_in(in_variants: &[FlatVariant], variant_idx: usize, input: &InputVal) -> IoRec {
    let vi = &in_variants[variant_idx];
    IoRec {
        variant: vi.unique_name.clone(),
        fields: vi
            .fields
            .iter()
            .map(|(n, _)| n.clone())
            .zip(input.fields.iter().cloned())
            .collect(),
    }
}

/// Convert one output to its wire record for the renderers.
fn io_out(out_variants: &[FlatVariant], o: &OutputVal) -> IoRec {
    let vi = &out_variants[o.variant];
    IoRec {
        variant: vi.unique_name.clone(),
        fields: vi
            .fields
            .iter()
            .map(|(n, _)| n.clone())
            .zip(o.fields.iter().cloned())
            .collect(),
    }
}

/// Render the per-run property-violation report in the generated byte format.
fn render_violation_report(
    module: &Module,
    run: usize,
    label: &str,
    trigger: Option<usize>,
    step: usize,
    q0: usize,
    init_vars: &[Val],
    trace: &[TraceStep],
) -> String {
    let in_variants = flatten(&module.events);
    let out_variants = flatten(&module.outputs);
    let state_names = state_variants(module).to_vec();
    // vars_at(pos): 0 = initial vars, n = post-step-(n-1) vars.
    let vars_at = |pos: usize| -> String {
        if pos == 0 {
            render_vars(module, init_vars)
        } else {
            render_vars(module, &trace[pos - 1].vars)
        }
    };
    let mut out = format!("run {run} property violation: {label}\n");
    if let Some(t) = trigger {
        out.push_str(&format!("  trigger step: {t}\n"));
        out.push_str(&format!("  vars at trigger step: {}\n", vars_at(t)));
    }
    out.push_str(&format!("  violation step: {step}\n"));
    out.push_str(&format!("  vars at violation step: {}\n", vars_at(step)));
    out.push_str("counterexample trace:\n");
    out.push_str(&format!(
        "  initial state=State::{} vars={}\n",
        state_names[q0],
        render_vars(module, init_vars)
    ));
    for (i, st) in trace.iter().enumerate() {
        let io = io_in(&in_variants, st.input.variant, &st.input);
        let outputs: Vec<IoRec> = st
            .outputs
            .iter()
            .map(|o| io_out(&out_variants, o))
            .collect();
        out.push_str(&format!(
            "  step {} input={} outputs={} from=State::{} to=State::{} vars={}\n",
            i,
            render_input(&io, &in_variants),
            render_outputs(&outputs, &out_variants),
            state_names[st.from_state],
            state_names[st.to_state],
            render_vars(module, &st.vars)
        ));
    }
    out
}

/// Step the FSM with ONE input under the given assumption policy, mirroring
/// the generated `commit_step`: push the trace step, step the SELECTED
/// assumption monitors (Stop => AssumptionViolation, Continue => proceed),
/// then the property monitors (first fire wins), else commit state/vars.
fn step_fsm(
    module: &Module,
    fsm: &mut FuzzFsm,
    input: &InputVal,
    sample_idx: usize,
    selected: &[String],
    continue_assumptions: bool,
    prop_specs: &[(String, Mon)],
    assume_specs: &[(String, Mon)],
) -> Result<(), StepErr> {
    let eff = match_effect(module, fsm.state, &fsm.vars, input).ok_or(StepErr::UnexpectedEvent)?;
    let sample = Sample {
        input: Some(input.clone()),
        outputs: eff.outputs.clone(),
        to_state: eff.next_state,
        vars: eff.next_vars.clone(),
    };
    // Record the step BEFORE the monitor checks (the generated runtime pushes
    // the trace step first, so a violating step is still in the trace).
    fsm.trace.push(TraceStep {
        input: input.clone(),
        outputs: eff.outputs.clone(),
        from_state: fsm.state,
        to_state: eff.next_state,
        vars: eff.next_vars.clone(),
    });
    // Assumptions first (selected only), Stop/Continue policy. An internal
    // monitor failure means "not fired" (validated specs always evaluate - the
    // same convention as match_effect's "no match").
    for (ai, (label, spec)) in assume_specs.iter().enumerate() {
        if !selected.iter().any(|x| x == label) {
            continue;
        }
        if mon_step(
            &mut fsm.assume_mons[ai],
            spec,
            sample_idx as u64,
            &sample,
            module,
        )
        .unwrap_or(false)
        {
            if !continue_assumptions {
                return Err(StepErr::AssumptionViolation(label.clone()));
            }
        }
    }
    // Then properties (first fire wins).
    for (pi, (label, spec)) in prop_specs.iter().enumerate() {
        if mon_step(
            &mut fsm.prop_mons[pi],
            spec,
            sample_idx as u64,
            &sample,
            module,
        )
        .unwrap_or(false)
        {
            let t = fsm.prop_mons[pi].trigger_step();
            return Err(StepErr::PropertyViolation {
                label: label.clone(),
                trigger: (t >= 0).then_some(t as usize),
                step: sample_idx,
            });
        }
    }
    fsm.state = eff.next_state;
    fsm.vars = eff.next_vars;
    Ok(())
}

/// Run the seeded fuzz engine over `cfg.runs` runs of `cfg.bound` steps each.
/// Returns the report (summary or per-run violation). `Err` for an assumption
/// already violated at the initial configuration (the generated binaries
/// panic/abort there; a CLI tool reports a clean error instead).
pub(crate) fn run(module: &Module, cfg: &FuzzConfig) -> Result<FuzzReport, String> {
    let (q0, init_vars) = initial_config(module)?;
    // ONE representative input per variant (the generated ALL_INPUTS) - NOT the
    // full domain Cartesian product; the draw sequence parity depends on it.
    let inputs = fuzz_inputs(module);

    // Compile the monitor banks: safety properties (declaration order) and ALL
    // assumptions (the selection filters at step time, mirroring the generated
    // `active_assumes`). Liveness properties carry no online monitor in fuzz
    // mode (the generated runtimes only monitor safety here).
    let mut prop_specs: Vec<(String, Mon)> = Vec::new();
    for p in &module.properties {
        if contains_liveness(&p.formula) {
            continue;
        }
        if let Ok(mon) = compile_formula(&p.formula) {
            prop_specs.push((p.name.clone(), mon));
        }
    }
    let mut assume_specs: Vec<(String, Mon)> = Vec::new();
    for a in &module.assumptions {
        if let Ok(mon) = compile_formula(&a.formula) {
            assume_specs.push((a.name.clone(), mon));
        }
    }
    let known: Vec<&str> = module.assumptions.iter().map(|a| a.name.as_str()).collect();
    let selected = parse_assume_selection(&cfg.assume_arg, &known);

    let mut rng = Rng::new(cfg.seed);
    // property_violations is always 0 (a violation exits immediately); the
    // field stays for a stable summary format.
    let property_violations = 0usize;
    let mut unexpected_count = 0usize;
    let mut assumption_stops = 0usize;
    let mut completed = 0usize;

    for run in 0..cfg.runs {
        // (1) Per-spec activation draws, in order.
        let violating: Vec<bool> = cfg.violate.iter().map(|s| rng.chance(s.prob)).collect();
        let target_fraction: Vec<f64> = cfg.violate.iter().map(|s| s.percent / 100.0).collect();

        // Fresh FSM: re-init the monitor banks, then step sample 0 with ALL
        // assumptions (parity with the generated Fsm::new, which runs before
        // the selection is applied).
        let mut prop_mons: Vec<MonSt> = prop_specs.iter().map(|(_, m)| mon_init(m)).collect();
        let mut assume_mons: Vec<MonSt> = assume_specs.iter().map(|(_, m)| mon_init(m)).collect();
        let sample0 = Sample {
            input: None,
            outputs: Vec::new(),
            to_state: q0,
            vars: init_vars.clone(),
        };
        for (ai, (label, spec)) in assume_specs.iter().enumerate() {
            if mon_step(&mut assume_mons[ai], spec, 0, &sample0, module)? {
                return Err(format!(
                    "assumption '{label}' violated at initial configuration (sample 0)"
                ));
            }
        }
        // A property can already be violated at sample 0.
        let mut pv0: Option<(String, Option<usize>)> = None;
        for (pi, (label, spec)) in prop_specs.iter().enumerate() {
            if mon_step(&mut prop_mons[pi], spec, 0, &sample0, module)? {
                let t = prop_mons[pi].trigger_step();
                pv0 = Some((label.clone(), (t >= 0).then_some(t as usize)));
                break;
            }
        }
        if let Some((label, trigger)) = pv0 {
            return Ok(FuzzReport::Violated {
                report: render_violation_report(
                    module,
                    run,
                    &label,
                    trigger,
                    0,
                    q0,
                    &init_vars,
                    &[],
                ),
            });
        }

        let mut fsm = FuzzFsm {
            state: q0,
            vars: init_vars.clone(),
            prop_mons,
            assume_mons,
            trace: Vec::new(),
        };
        let mut status_completed = true;

        for step in 0..cfg.bound {
            let sample_idx = step + 1;
            // (2a) Forced-violation phase: per active spec, a fraction draw then
            // a DRAW-FREE scan for an input whose trial yields the spec's label.
            let mut forced: Option<InputVal> = None;
            for (idx, spec) in cfg.violate.iter().enumerate() {
                if violating[idx] && rng.chance(target_fraction[idx]) {
                    for input in &inputs {
                        let mut trial = fsm.clone();
                        match step_fsm(
                            module,
                            &mut trial,
                            input,
                            sample_idx,
                            &selected,
                            false,
                            &prop_specs,
                            &assume_specs,
                        ) {
                            Err(StepErr::AssumptionViolation(l)) if l == spec.label => {
                                forced = Some(input.clone());
                                break;
                            }
                            Err(StepErr::PropertyViolation { label, .. })
                                if label == spec.label =>
                            {
                                forced = Some(input.clone());
                                break;
                            }
                            _ => {}
                        }
                    }
                    if forced.is_some() {
                        break;
                    }
                }
            }
            if let Some(input) = forced {
                // Step the real FSM with the Stop handler.
                match step_fsm(
                    module,
                    &mut fsm,
                    &input,
                    sample_idx,
                    &selected,
                    false,
                    &prop_specs,
                    &assume_specs,
                ) {
                    Err(StepErr::AssumptionViolation(_)) => {
                        status_completed = false;
                        assumption_stops += 1;
                        break;
                    }
                    Err(StepErr::PropertyViolation {
                        label,
                        trigger,
                        step,
                    }) => {
                        return Ok(FuzzReport::Violated {
                            report: render_violation_report(
                                module, run, &label, trigger, step, q0, &init_vars, &fsm.trace,
                            ),
                        });
                    }
                    _ => {}
                }
                continue;
            }

            // (2b) Unexpected-injection phase.
            if rng.chance(cfg.unexpected_prob) {
                if let Some(idx) = rng.pick_index(inputs.len()) {
                    let input = inputs[idx].clone();
                    match step_fsm(
                        module,
                        &mut fsm,
                        &input,
                        sample_idx,
                        &selected,
                        true,
                        &prop_specs,
                        &assume_specs,
                    ) {
                        Err(StepErr::UnexpectedEvent) => {
                            status_completed = false;
                            unexpected_count += 1;
                            break;
                        }
                        Err(StepErr::PropertyViolation {
                            label,
                            trigger,
                            step,
                        }) => {
                            return Ok(FuzzReport::Violated {
                                report: render_violation_report(
                                    module, run, &label, trigger, step, q0, &init_vars, &fsm.trace,
                                ),
                            });
                        }
                        _ => {}
                    }
                }
                continue;
            }

            // (2c) Allowed phase: draw-free scan builds the allowed list (Ok or
            // PropertyViolation inputs are allowed on purpose), then pick one.
            let mut allowed: Vec<InputVal> = Vec::new();
            for input in &inputs {
                let mut trial = fsm.clone();
                match step_fsm(
                    module,
                    &mut trial,
                    input,
                    sample_idx,
                    &selected,
                    false,
                    &prop_specs,
                    &assume_specs,
                ) {
                    Ok(()) => allowed.push(input.clone()),
                    Err(StepErr::PropertyViolation { .. }) => allowed.push(input.clone()),
                    _ => {}
                }
            }
            if allowed.is_empty() {
                status_completed = false;
                break; // stuck
            }
            if let Some(idx) = rng.pick_index(allowed.len()) {
                let input = allowed[idx].clone();
                match step_fsm(
                    module,
                    &mut fsm,
                    &input,
                    sample_idx,
                    &selected,
                    false,
                    &prop_specs,
                    &assume_specs,
                ) {
                    Ok(()) => {}
                    Err(StepErr::UnexpectedEvent) => {
                        status_completed = false;
                        unexpected_count += 1;
                        break;
                    }
                    Err(StepErr::AssumptionViolation(_)) => {
                        status_completed = false;
                        assumption_stops += 1;
                        break;
                    }
                    Err(StepErr::PropertyViolation {
                        label,
                        trigger,
                        step,
                    }) => {
                        return Ok(FuzzReport::Violated {
                            report: render_violation_report(
                                module, run, &label, trigger, step, q0, &init_vars, &fsm.trace,
                            ),
                        });
                    }
                }
            }
        }
        if status_completed {
            completed += 1;
        }
    }

    Ok(FuzzReport::Completed {
        summary: fuzz_summary_line(
            cfg.runs,
            cfg.bound,
            completed,
            unexpected_count,
            assumption_stops,
            property_violations,
        ),
    })
}

