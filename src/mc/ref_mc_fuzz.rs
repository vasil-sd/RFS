#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse_source;

    fn module(src: &str) -> Module {
        parse_source(src)
            .expect("parse")
            .modules
            .pop()
            .expect("module")
    }

    fn cfg() -> FuzzConfig {
        FuzzConfig::default()
    }

    /// No properties, no assumptions, one always-allowed input: every run
    /// completes. Pins the summary-line bytes and the completed counter.
    #[test]
    fn all_runs_complete() {
        let m = module(
            "module m { enum State { A } initial A event Go \
             transition A on Go { next A; } }",
        );
        let c = FuzzConfig {
            runs: 7,
            bound: 3,
            ..cfg()
        };
        match run(&m, &c).expect("run") {
            FuzzReport::Completed { summary } => assert_eq!(
                summary,
                "model-check summary: runs=7 bound=3 completed=7 unexpected=0 assumption_stops=0 property_violations=0"
            ),
            other => panic!("expected Completed, got {:?}", other),
        }
    }

    /// A --violate directive at prob=1.0/percent=100% forces an assumption
    /// violation on every run's first step: assumption_stops = runs, completed = 0.
    /// The assumption is violated by a SUCCESSFUL step (input Go sets x=1,
    /// breaking always(x==0)) - an unmatched input would be UnexpectedEvent
    /// before the monitor fires.
    #[test]
    fn forced_violation_hits_every_run() {
        let m = module(
            "module m { enum State { A } initial A \
             event Go \
             event Bad \
             var x: bit<1> init 0 \
             transition A on Go { next A; set x = 1; } \
             transition A on Bad { next A; set x = 0; } \
             assume env_x : always (x == 0) ; }",
        );
        // Force the assumption 'env_x': input Go steps to x=1, violating it.
        // prob=1.0, percent=100% => every run, every step attempts the force.
        let c = FuzzConfig {
            runs: 5,
            bound: 4,
            violate: vec![crate::codegen::mc_concepts::ViolationSpec::parse(
                "env_x:1.0:100%",
            )],
            ..cfg()
        };
        match run(&m, &c).expect("run") {
            FuzzReport::Completed { summary } => assert_eq!(
                summary,
                "model-check summary: runs=5 bound=4 completed=0 unexpected=0 assumption_stops=5 property_violations=0"
            ),
            other => panic!("expected Completed, got {:?}", other),
        }
    }

    /// --unexpected-prob 1.0 with the ONLY input unexpected (no on_error): the
    /// unexpected phase fires every step and always lands an UnexpectedEvent.
    #[test]
    fn unexpected_injection_every_step() {
        // 'Only' does not match the 'Go' transition => unexpected (no on_error).
        let m = module(
            "module m { enum State { A } initial A event Only \
             transition A on Go { next A; } }",
        );
        let c = FuzzConfig {
            runs: 6,
            bound: 2,
            unexpected_prob: 1.0,
            ..cfg()
        };
        match run(&m, &c).expect("run") {
            FuzzReport::Completed { summary } => assert_eq!(
                summary,
                "model-check summary: runs=6 bound=2 completed=0 unexpected=6 assumption_stops=0 property_violations=0"
            ),
            other => panic!("expected Completed, got {:?}", other),
        }
    }

    /// unexpected_prob=0 and NO allowed input (the only input is unexpected):
    /// the allowed phase finds an empty list => stuck, completed=0.
    #[test]
    fn no_allowed_input_is_stuck() {
        let m = module(
            "module m { enum State { A } initial A event Only \
             transition A on Go { next A; } }",
        );
        let c = FuzzConfig {
            runs: 4,
            bound: 3,
            ..cfg()
        };
        match run(&m, &c).expect("run") {
            FuzzReport::Completed { summary } => assert_eq!(
                summary,
                "model-check summary: runs=4 bound=3 completed=0 unexpected=0 assumption_stops=0 property_violations=0"
            ),
            other => panic!("expected Completed, got {:?}", other),
        }
    }

    /// A property violated at step 1 renders the exact per-run report and exits
    /// with NO summary line. Byte-pins the report format (the cross-backend
    /// diff suite re-verifies this against both generated binaries).
    #[test]
    fn property_violation_report_bytes() {
        let m = module(
            "module m { enum State { A, B } initial A event Go \
             var x: bit<1> init 0 \
             transition A on Go { next B; set x = 1; } \
             transition B on Go { next B; } \
             prop p : always (x == 0) ; }",
        );
        let c = FuzzConfig {
            runs: 1,
            bound: 5,
            ..cfg()
        };
        match run(&m, &c).expect("run") {
            FuzzReport::Violated { report } => assert_eq!(
                report,
                "run 0 property violation: p\n  violation step: 1\n  vars at violation step: Vars { x: 1 }\ncounterexample trace:\n  initial state=State::A vars=Vars { x: 0 }\n  step 0 input=Input::Go outputs=[] from=State::A to=State::B vars=Vars { x: 1 }\n"
            ),
            other => panic!("expected Violated, got {:?}", other),
        }
    }
}
